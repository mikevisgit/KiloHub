// Synthetic disk discovery only; no production imports, source paths or real data.
const assert = require('node:assert/strict');
const process = require('node:process');
const console = require('node:console');
const { Buffer } = require('node:buffer');
const { mkdtempSync, rmSync, statSync, existsSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { performance } = require('node:perf_hooks');
const { setTimeout: delay } = require('node:timers/promises');
const { setTimeout, clearTimeout } = require('node:timers');
const { Worker, isMainThread, parentPort, workerData } = require('node:worker_threads');
const { DatabaseSync } = require('node:sqlite');

const normalize = (text) => text.normalize('NFC').toLowerCase().replace(/\u0451/g, '\u0435').normalize('NFC');
const phrase = (token) => `"${token.replace(/"/g, '""')}"`;
const round = (value) => Math.round(value * 100) / 100;
const folders = 1000;
const busyMs = 80;
const batchRows = 1000;
function request(text) {
  const tokens = [...new Set(normalize(text).trim().split(/\s+/u).filter(Boolean))];
  return { status: !tokens.length ? 'reset' : tokens.some((token) => [...token].length < 3) ? 'invalid' : 'search', tokens };
}
function combine(maps) {
  return [...maps[0]].filter(([id]) => maps.every((map) => map.has(id)))
    .map(([id]) => [id, Math.max(...maps.map((map) => map.get(id)))])
    .sort((a, b) => a[0] - b[0]);
}
function summary(values) {
  const sorted = [...values].sort((a, b) => a - b);
  return { n: sorted.length, medianMs: round(sorted[Math.floor(sorted.length / 2)]),
    p95Ms: round(sorted[Math.ceil(sorted.length * 0.95) - 1]), maxMs: round(sorted.at(-1)) };
}

async function workerMain() {
  // The path is generated by this script's parent, never accepted on the command line.
  const db = new DatabaseSync(workerData.path);
  db.exec(`PRAGMA busy_timeout=${busyMs}`);
  const update = db.prepare('UPDATE fields SET text = ? WHERE id IN (110999, 111000)');
  const messages = [];
  let wake;
  parentPort.on('message', (message) => { messages.push(message); if (wake) wake(); });
  const next = async () => {
    if (!messages.length) await new Promise((resolve) => { wake = resolve; });
    wake = undefined;
    return messages.shift();
  };
  const change = (revision) => {
    db.exec('BEGIN IMMEDIATE');
    update.run(`writerrevision${revision}`);
    db.prepare('UPDATE state SET revision=?').run(revision);
  };
  parentPort.postMessage({ type: 'ready' });
  try {
    for (;;) {
      const { command } = await next();
      if (command === 'close') break;
      if (command === 'hold') {
        change(1);
        parentPort.postMessage({ type: 'held' });
      } else if (command === 'release') {
        db.exec('COMMIT');
        parentPort.postMessage({ type: 'released' });
      } else if (command === 'run') {
        const startedAt = performance.timeOrigin + performance.now();
        const times = [];
        let busy = 0;
        parentPort.postMessage({ type: 'running' });
        for (let revision = 2; revision <= 41; revision++) {
          const start = performance.now();
          try { change(revision); db.exec('COMMIT'); }
          catch (error) {
            if (db.isTransaction) db.exec('ROLLBACK');
            if (error.errcode !== 5) throw error;
            busy++;
          }
          times.push(performance.now() - start);
          await delay(10);
        }
        parentPort.postMessage({ type: 'written', busy, attempts: times.length, timings: summary(times),
          startedAt, finishedAt: performance.timeOrigin + performance.now() });
      } else if (command === 'bounded') {
        const revision = 7;
        const control = new Int32Array(workerData.control);
        const chunk = db.prepare('SELECT count(*) AS n FROM fields WHERE id > ? AND id <= ? AND instr(text, ?) > 0');
        let chunks = 0;
        let maxChunkMs = 0;
        db.exec('BEGIN');
        try {
          for (let start = 0; start < 111000; start += batchRows) {
            if (Atomics.load(control, 0) !== revision) break;
            const began = performance.now();
            chunk.get(start, start + batchRows, 'common');
            maxChunkMs = Math.max(maxChunkMs, performance.now() - began);
            chunks++;
            if (chunks === 1) {
              parentPort.postMessage({ type: 'chunk', revision });
              // Deterministic supersession between bounded SQL calls, not sqlite interruption.
              assert.equal((await next()).command, 'continue');
            }
          }
        } finally { db.exec('ROLLBACK'); }
        parentPort.postMessage({ type: 'boundedDone', revision, chunks, maxChunkMs: round(maxChunkMs),
          cancelled: Atomics.load(control, 0) !== revision });
      } else if (command === 'result') {
        parentPort.postMessage({ type: 'result', revision: 8,
          count: db.prepare("SELECT count(*) AS n FROM fields WHERE instr(text, 'rankneedle') > 0").get().n });
      } else throw new Error('Unknown synthetic worker command');
    }
  } finally {
    if (db.isTransaction) db.exec('ROLLBACK');
    db.close();
    parentPort.close();
  }
}

async function main() {
  assert.equal(process.argv.length, 2, 'No input paths or arguments permitted');
  assert.ok(process.versions.electron, 'Run using bundled Code.exe with ELECTRON_RUN_AS_NODE=1');
  const started = performance.now();
  const root = mkdtempSync(join(tmpdir(), 'kilo-hub-synthetic-disk-'));
  const path = join(root, 'synthetic.db');
  const connections = [];
  let worker;
  let watchdog;
  const report = {};
  const cleanupErrors = [];
  try {
    const db = new DatabaseSync(path);
    connections.push(db);
    assert.equal(db.prepare('PRAGMA journal_mode=WAL').get().journal_mode, 'wal');
    db.exec(`PRAGMA synchronous=NORMAL; PRAGMA wal_autocheckpoint=0; PRAGMA busy_timeout=${busyMs};
      CREATE TABLE fields(id INTEGER PRIMARY KEY, folder INTEGER NOT NULL, kind INTEGER NOT NULL, text TEXT NOT NULL, has_nul INTEGER NOT NULL);
      CREATE INDEX nul_fields ON fields(has_nul) WHERE has_nul=1;
      CREATE TABLE state(revision INTEGER NOT NULL); INSERT INTO state VALUES(0)`);
    const rows = [];
    const special = new Map([
      ['0:0:0', '\u0421\u0410\u0419\u0422 nameonly'],
      ['0:1:0', '\u041a\u043e\u0440\u0437\u0438\u043d\u0430 \u0437\u0430\u043a\u0430\u0437 titleonly'],
      ['0:1:9', '\u0432\u043e\u0437\u0432\u0440\u0430\u0442 oldtitle'],
      ['0:2:0', '\u0414\u043e\u0431\u0430\u0432\u0438\u0442\u044c \u043e\u043f\u043b\u0430\u0442\u0443 \u0401\u0436\u0438\u043a Cafe\u0301 %_* "quoted" a"b O\'Reilly'],
      ['0:2:1', 'separatepart crossalpha'], ['0:2:99', 'crossbeta oldmessage'],
      ['1:2:0', 'leftunique boundaryleft'], ['1:2:1', 'boundaryright'],
      ['2:2:0', 'rightunique'], ['3:2:0', 'abXbcXcd'],
      ['4:2:0', '\ud83d\ude80\ud83d\ude80\ud83d\ude80 \u0130stanbul'],
      ['5:0:0', 'rankneedle'], ['6:1:0', 'rankneedle'], ['7:2:0', 'rankneedle'],
      ['8:2:0', 'nulbefore\0nulafter'], ['9:2:0', 'abc\0def'],
    ]);
    let bytes = 0;
    let longest = 0;
    for (let folder = 0; folder < folders; folder++) {
      for (const [kind, count] of [[0, 1], [1, 10], [2, 100]]) {
        for (let part = 0; part < count; part++) {
          let raw = special.get(`${folder}:${kind}:${part}`);
          if (raw === undefined) {
            raw = `Synthetic ${['folder', 'title', 'user'][kind]} ${folder} item ${part} group${folder % 31} common `;
            if (kind === 2) raw += `Generated payload segment${part % 17} stable reproducible text for substring testing. `.repeat(2);
            if (kind === 2 && part === 98 && folder % 10 === 0) raw += 'long synthetic content '.repeat(800) + 'longtailmarker';
          }
          const text = normalize(raw);
          bytes += Buffer.byteLength(text);
          longest = Math.max(longest, Buffer.byteLength(text));
          rows.push({ id: rows.length + 1, folder, kind, text });
        }
      }
    }
    const insert = db.prepare('INSERT INTO fields VALUES(?,?,?,?,?)');
    let begin = performance.now();
    db.exec('BEGIN');
    for (const row of rows) insert.run(row.id, row.folder, row.kind, row.text, Number(row.text.includes('\0')));
    db.exec('COMMIT');
    const loadMs = performance.now() - begin;
    const size = () => db.prepare('PRAGMA page_count').get().page_count * db.prepare('PRAGMA page_size').get().page_size;
    const baseBytes = size();
    begin = performance.now();
    db.exec(`CREATE VIRTUAL TABLE grams USING fts5(text, content='fields', content_rowid='id', tokenize='trigram case_sensitive 1');
      INSERT INTO grams(grams) VALUES('rebuild');
      CREATE TRIGGER fields_update AFTER UPDATE ON fields BEGIN
        INSERT INTO grams(grams,rowid,text) VALUES('delete',old.id,old.text);
        INSERT INTO grams(rowid,text) VALUES(new.id,new.text);
      END;`);
    const indexMs = performance.now() - begin;
    const indexedBytes = size();
    db.exec('PRAGMA wal_checkpoint(TRUNCATE)'); // Only our generated synthetic DB.
    const reader = new DatabaseSync(path, { readOnly: true });
    connections.push(reader);
    reader.exec(`PRAGMA query_only=ON; PRAGMA busy_timeout=${busyMs}`);
    const literal = reader.prepare('SELECT folder,min(kind) AS kind FROM fields WHERE instr(text,?)>0 GROUP BY folder');
    // NUL can truncate FTS tokenization: include every NUL field as a candidate.
    const trigram = reader.prepare(`SELECT folder,min(kind) AS kind FROM fields WHERE id IN (
      SELECT rowid FROM grams WHERE grams MATCH ? UNION SELECT id FROM fields WHERE has_nul=1
      ) AND instr(text,?)>0 GROUP BY folder`);
    let sqlCalls = 0;
    const search = (text, fts) => {
      const parsed = request(text);
      if (parsed.status !== 'search') return { status: parsed.status };
      const maps = parsed.tokens.map((token) => {
        sqlCalls++;
        const result = fts && !token.includes('\0') ? trigram.all(phrase(token), token) : literal.all(token);
        return new Map(result.map((row) => [row.folder, row.kind]));
      });
      return { status: 'search', matches: combine(maps) };
    };
    const oracle = (text) => {
      const parsed = request(text);
      if (parsed.status !== 'search') return { status: parsed.status };
      return { status: 'search', matches: combine(parsed.tokens.map((token) => {
        const map = new Map();
        for (const row of rows) if (row.text.includes(token)) map.set(row.folder, Math.min(map.get(row.folder) ?? 2, row.kind));
        return map;
      })) };
    };
    const cases = [
      ['reset', ''], ['reset', ' \t\n '],
      ...['a', 'sy', '\u0451\u0436', '\ud83d\ude80', '\ud83d\ude80\ud83d\ude80', 'nameonly %', 'common ab', 'ab common', 'cafe\u0301 e\u0301', '" OR *'].map((q) => ['invalid', q]),
      ...['%_*', '"quoted"', 'a"b', "O'Reilly", "';DROP"].map((q) => ['literal', q]),
      ...['\u0401\u0416\u0418\u041a', 'CAF\u00c9', 'CAFE\u0301', '\ud83d\ude80\ud83d\ude80\ud83d\ude80', '\u0130STANBUL'].map((q) => ['unicode', q]),
      ...['\u0421\u0410\u0419\u0422 \u043e\u043f\u043b\u0430\u0442', '\u0437\u0430\u043a\u0430\u0437 \u0432\u043e\u0437\u0432\u0440\u0430\u0442', 'crossalpha crossbeta', 'nameonly titleonly oldmessage', ' NAMEONLY\tnameonly\noldtitle '].map((q) => ['and', q]),
      ...['leftunique rightunique', 'boundaryleftboundaryright', 'abcd', 'pathonlynotindexed', 'absentneedle'].map((q) => ['negative', q]),
      ...['rankneedle', 'group17 segment13', 'oldmessage'].map((q) => ['selective', q]),
      ...['common', 'synthetic', 'synthetic common text'].map((q) => ['broad', q]),
      ['long', 'longtailmarker'], ['long', 'content'.repeat(1000)],
      ...['nulbefore', 'nulafter', 'abc\0def', '\0de', 'beforenulafter'].map((q) => ['nul', q]),
    ];
    const expected = cases.map(([, text]) => oracle(text));
    assert.deepEqual(search('rankneedle', true).matches, [[5, 0], [6, 1], [7, 2]]);
    let applied = search('nameonly', true);
    const previous = applied;
    let invalidChecks = 0;
    for (const [category, text] of cases) if (category === 'invalid' || category === 'reset') {
      for (const fts of [false, true]) {
        const before = sqlCalls;
        const result = search(text, fts);
        assert.equal(result.status, category);
        assert.equal(sqlCalls, before);
        if (result.status !== 'invalid') applied = result;
        else assert.equal(applied, previous);
        applied = previous;
        invalidChecks++;
      }
    }
    const rawFtsNul = ['nulbefore', 'nulafter'].map((token) => ({
      position: token === 'nulbefore' ? 'before' : 'after',
      instrFolders: literal.all(token).length,
      ftsRows: reader.prepare('SELECT count(*) AS n FROM grams WHERE grams MATCH ?').get(phrase(token)).n,
    }));
    const rawNulQuery = { instrFolders: literal.all('abc\0def').length };
    try {
      rawNulQuery.ftsRows = reader.prepare('SELECT count(*) AS n FROM grams WHERE grams MATCH ?').get(phrase('abc\0def')).n;
    } catch (error) { rawNulQuery.sqliteErrorCode = error.errcode; }
    const samples = new Map();
    let comparisons = 0;
    const benchmark = (phase, rounds) => {
      for (let repeat = 0; repeat < rounds; repeat++) {
        for (let i = 0; i < cases.length; i++) {
          const [category, text] = cases[i];
          for (const fts of repeat % 2 ? [true, false] : [false, true]) {
            const start = performance.now();
            const result = search(text, fts);
            const ms = performance.now() - start;
            assert.deepEqual(result, expected[i]);
            comparisons++;
            const key = `${phase}/${category}/${fts ? 'fts+instr+nul-fallback' : 'instr'}`;
            if (!samples.has(key)) samples.set(key, []);
            samples.get(key).push(ms);
          }
        }
      }
    };
    benchmark('first-pass-not-cold', 1);
    benchmark('warm', 3);

    const control = new SharedArrayBuffer(4);
    const revision = new Int32Array(control);
    const inbox = [];
    let waiter;
    let workerError;
    worker = new Worker(require.resolve('./step3-disk-search.cjs'), { workerData: { path, control } });
    worker.on('message', (message) => { inbox.push(message); if (waiter) waiter(); });
    worker.on('error', (error) => { workerError = error; if (waiter) waiter(); });
    worker.on('exit', (code) => { workerError ??= new Error(`Worker exited (${code})`); if (waiter) waiter(); });
    const receive = async (type) => {
      if (!inbox.length && !workerError) {
        await new Promise((resolve, reject) => {
          watchdog = setTimeout(() => reject(new Error(`Worker deadline: ${type}`)), 15000);
          waiter = resolve;
        }).finally(() => { clearTimeout(watchdog); waiter = undefined; });
      }
      if (workerError) throw workerError;
      const message = inbox.shift();
      assert.equal(message.type, type);
      return message;
    };
    const send = (command) => worker.postMessage({ command });
    await receive('ready');
    reader.exec('BEGIN');
    const snapshot = reader.prepare('SELECT revision FROM state');
    assert.equal(snapshot.get().revision, 0);
    send('hold');
    await receive('held');
    begin = performance.now();
    assert.equal(snapshot.get().revision, 0);
    assert.equal(db.prepare('SELECT revision FROM state').get().revision, 0);
    const readWhileWriterMs = performance.now() - begin;
    begin = performance.now();
    assert.throws(() => db.exec('BEGIN IMMEDIATE'), (error) => error.errcode === 5);
    const writerBusyMs = performance.now() - begin;
    assert.ok(writerBusyMs < 5000, 'Observed lock wait must remain bounded');
    send('release');
    await receive('released');
    assert.equal(snapshot.get().revision, 0);
    assert.equal(search('writerrevision1', true).matches.length, 0);
    reader.exec('COMMIT');
    assert.equal(snapshot.get().revision, 1);
    assert.deepEqual(search('writerrevision1', true), search('writerrevision1', false));
    assert.equal(search('writerrevision1', true).matches.length, 1);
    db.exec('BEGIN IMMEDIATE; ROLLBACK');

    // Hold one read snapshot while the worker commits. Compare against its JS oracle.
    for (const row of rows) if (row.id >= 110999) row.text = 'writerrevision1';
    for (let i = 0; i < cases.length; i++) expected[i] = oracle(cases[i][1]);
    reader.exec('BEGIN');
    assert.equal(snapshot.get().revision, 1);
    send('run');
    await receive('running');
    const concurrentStartedAt = performance.timeOrigin + performance.now();
    benchmark('concurrent-snapshot', 1);
    const concurrentFinishedAt = performance.timeOrigin + performance.now();
    const written = await receive('written');
    const writerOverlapMs = Math.min(concurrentFinishedAt, written.finishedAt) - Math.max(concurrentStartedAt, written.startedAt);
    assert.ok(writerOverlapMs > 0, 'Writer burst must overlap benchmark interval');
    assert.equal(written.busy, 0);
    assert.equal(snapshot.get().revision, 1);
    assert.equal(db.prepare('SELECT revision FROM state').get().revision, 41);
    const walBytes = statSync(`${path}-wal`).size;
    reader.exec('COMMIT');
    assert.equal(snapshot.get().revision, 41);
    assert.equal(search('writerrevision1', true).matches.length, 0);
    assert.deepEqual(search('writerrevision41', true), search('writerrevision41', false));
    assert.equal(search('writerrevision41', true).matches.length, 1);

    Atomics.store(revision, 0, 7);
    send('bounded');
    await receive('chunk');
    begin = performance.now();
    Atomics.store(revision, 0, 8);
    send('continue');
    const cancelled = await receive('boundedDone');
    const cancelMs = performance.now() - begin;
    assert.equal(cancelled.cancelled, true);
    assert.equal(cancelled.chunks, 1);
    send('result');
    const stale = await receive('result');
    assert.equal(stale.count, 3);
    const currentRevision = 9;
    let published = 'latest-result';
    if (stale.revision === currentRevision) published = stale.count;
    assert.equal(published, 'latest-result');
    send('close');
    const exitCode = await new Promise((resolve, reject) => {
      watchdog = setTimeout(() => reject(new Error('Worker close deadline')), 15000);
      worker.once('exit', resolve);
    }).finally(() => clearTimeout(watchdog));
    assert.equal(exitCode, 0);
    worker = undefined;
    const checkpoint = db.prepare('PRAGMA wal_checkpoint(TRUNCATE)').get();
    assert.equal(checkpoint.busy, 0);
    assert.equal(statSync(`${path}-wal`).size, 0);
    Object.assign(report, {
      evidence: 'Synthetic temporary disk WAL on bundled Electron Node; NOT Extension Host / installed VSIX / production proof',
      runtime: { node: process.versions.node, electron: process.versions.electron,
        sqlite: db.prepare('SELECT sqlite_version() AS v').get().v, platform: process.platform, arch: process.arch },
      corpus: { folders, titles: 10000, userTextFields: 100000, totalFields: rows.length, normalizedUtf8Bytes: bytes, longestFieldBytes: longest },
      setup: { loadMs: round(loadMs), indexMs: round(indexMs), baseBytes, indexedBytes, ftsAdditionalBytes: indexedBytes - baseBytes },
      validation: { cases: cases.length, oracleComparisons: comparisons, noSqlInvalidResetChecks: invalidChecks, rawFtsNul, rawNulQuery },
      concurrency: { writerAttempts: written.attempts, writerBusy: written.busy, writerTimings: written.timings,
        readWhileWriterMs: round(readWhileWriterMs), forcedWriterBusyMs: round(writerBusyMs), busyTimeoutMs: busyMs,
        writerBurstOverlapMs: round(writerOverlapMs), snapshotBenchmarkMs: round(concurrentFinishedAt - concurrentStartedAt),
        heldSnapshotRevision: 1, latestRevision: 41, walBytesWithPinnedReader: walBytes, checkpointAfterReaderRelease: checkpoint },
      cancellation: { strategy: 'revision check between bounded rowid SQL batches', batchRows,
        chunksBeforeCancel: cancelled.chunks, maxObservedChunkMs: cancelled.maxChunkMs,
        cancelHandshakeMs: round(cancelMs), staleResultDiscarded: true, cleanWorkerExit: exitCode },
      timings: [...samples].map(([categoryMode, values]) => ({ categoryMode, ...summary(values) })),
      elapsedMs: round(performance.now() - started), rssMiB: round(process.memoryUsage().rss / 1024 / 1024),
      limits: ['First disk pass is NOT cold OS cache; warmup/build already touched data',
        'NUL query uses instr scan; NUL fields are unioned into FTS candidates to avoid false negatives',
        'SQL per token needs one read transaction for consistent folder AND across concurrent commits',
        'Pinned snapshot grows WAL; production must bound reader lifetime and writer batches',
        'Cancellation is cooperative between SQL calls, NOT interruption of synchronous SQLite or worker termination proof',
        '1000 rows per chunk does not bound bytes or worst-case time for arbitrary long fields',
        'Finite writer burst overlaps benchmark, not necessarily every query; no crash/disk-full/profile/activation/recovery or production SLA claim',
        'Tier coverage tested, not current-first/activity tie-breakers or UI; RSS includes JS corpus/oracle',
        'No full Unicode case folding or malformed-surrogate guarantee; uses specified JS normalization'],
    });
  } finally {
    clearTimeout(watchdog);
    // Always close handles before deleting ONLY the unique root created above.
    try { if (worker) await worker.terminate(); }
    finally {
      try {
        for (const db of connections.reverse()) {
          try {
            try { if (db.isTransaction) db.exec('ROLLBACK'); }
            finally { db.close(); }
          } catch (error) { cleanupErrors.push(error); }
        }
      } finally { rmSync(root, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 }); }
    }
  }
  if (cleanupErrors.length) throw new AggregateError(cleanupErrors, 'Synthetic connection cleanup failed');
  assert.equal(existsSync(root), false);
  report.cleanup = { generatedTempRootRemoved: true };
  console.log(JSON.stringify(report, null, 2));
}

